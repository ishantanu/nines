// Package migrate converts SLO definitions from other tools into Nines SLO
// definitions. It is offline and deterministic: it saves nothing, contacts no
// provider and never guesses. Anything it cannot convert faithfully is
// reported as skipped with the reason, and every approximation is reported as
// a note. Imported SLOs start experimental so Nines does not page while the
// original tool's rules are still running.
package migrate

import (
	"bytes"
	"fmt"
	"math"
	"regexp"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"

	v1 "github.com/ishantanu/nines/api/v1alpha1"
	"github.com/ishantanu/nines/internal/model"
)

const (
	MaxInputBytes = 1 << 20
	MaxDocuments  = 50
	MaxSLOs       = 200
	stepSeconds   = 60
	stepText      = "1m"
	dayWindow     = int64(24 * 3600)
)

// Options are the import choices. Zero values select safe defaults.
type Options struct {
	Project       string
	Source        string
	WindowSeconds int64
	Lifecycle     string
}

func (o Options) normalize() (Options, error) {
	if o.Project == "" {
		o.Project = "production"
	}
	if o.Source == "" {
		o.Source = "primary"
	}
	if o.WindowSeconds == 0 {
		o.WindowSeconds = 30 * dayWindow
	}
	if o.Lifecycle == "" {
		o.Lifecycle = "experimental"
	}
	if o.WindowSeconds < 3600 || o.WindowSeconds > 31*dayWindow || o.WindowSeconds%stepSeconds != 0 {
		return o, fmt.Errorf("window must be between 1 hour and 31 days")
	}
	switch o.Lifecycle {
	case "experimental", "aspirational", "committed":
	default:
		return o, fmt.Errorf("lifecycle must be experimental, aspirational or committed")
	}
	return o, nil
}

// Convert converts definitions in the named tool's format.
func Convert(tool string, content []byte, opts Options) (v1.MigrationResult, error) {
	opts, err := opts.normalize()
	if err != nil {
		return v1.MigrationResult{}, err
	}
	if len(content) == 0 || len(content) > MaxInputBytes {
		return v1.MigrationResult{}, fmt.Errorf("provide between 1 byte and %d bytes of YAML", MaxInputBytes)
	}
	r := v1.MigrationResult{APIVersion: v1.APIVersion, Tool: tool, Definitions: []v1.MigrationDefinition{}, Skipped: []v1.MigrationSkipped{}, Notes: []v1.MigrationNote{}, Limitations: limitations()}
	if opts.Lifecycle == "experimental" {
		r.Notes = append(r.Notes, note("info", "lifecycle", "Imported SLOs start experimental: Nines measures them and generates recording rules but does not page. Run them beside the original rules, compare, then promote to committed and retire the old alerts."))
	}
	docs, err := documents(content)
	if err != nil {
		return r, err
	}
	var items []item
	switch tool {
	case "sloth":
		items, err = slothItems(docs, &r, opts)
	case "pyrra":
		items, err = pyrraItems(docs, &r, opts)
	default:
		return r, fmt.Errorf("tool must be sloth or pyrra")
	}
	if err != nil {
		return r, err
	}
	if len(items) > MaxSLOs {
		return r, fmt.Errorf("convert at most %d SLOs at a time", MaxSLOs)
	}
	used := map[string]bool{}
	for _, it := range items {
		name := unique(slug(it.name), used)
		it.spec["displayName"] = it.display
		def := map[string]any{
			"apiVersion": model.APIVersion,
			"kind":       "ServiceLevelObjective",
			"metadata":   map[string]any{"name": name, "project": opts.Project},
			"spec":       it.spec,
		}
		b, err := yaml.Marshal(def)
		if err != nil {
			return r, err
		}
		parsed, err := model.ParseDefinition(b)
		if err != nil || parsed.SLO == nil {
			reason := "the converted definition did not validate"
			if err != nil {
				reason += ": " + err.Error()
			}
			r.Skipped = append(r.Skipped, v1.MigrationSkipped{Origin: it.origin, Reason: reason})
			continue
		}
		r.Definitions = append(r.Definitions, v1.MigrationDefinition{Name: name, Origin: it.origin, YAML: string(b), Notes: it.notes})
	}
	return r, nil
}

func limitations() []string {
	return []string{
		"Conversion is offline. Nothing is saved, planned or applied; review each definition, then use plan and apply.",
		"Queries are converted only when they are sums of counter rates or increases. Other expressions are skipped, never rewritten.",
		"Nines evaluates good and total event counts per minute; a rate over the original window becomes an increase over one minute.",
		"Alert policies are standard multi-window burn-rate policies scaled to the SLO window. Custom alert names, labels and annotations are not carried over.",
		"Burn alerts are generated by Nines rules. Compare them with your current alerts before retiring either.",
	}
}

type item struct {
	origin  string
	name    string
	display string
	spec    map[string]any
	notes   []v1.MigrationNote
}

func note(level, field, msg string) v1.MigrationNote {
	return v1.MigrationNote{Level: level, Field: field, Message: msg}
}

// documents splits a multi-document YAML stream into nodes.
func documents(content []byte) ([]*yaml.Node, error) {
	dec := yaml.NewDecoder(bytes.NewReader(content))
	var out []*yaml.Node
	for {
		var n yaml.Node
		if err := dec.Decode(&n); err != nil {
			if err.Error() == "EOF" {
				break
			}
			return nil, fmt.Errorf("the YAML could not be read: %v", err)
		}
		if n.Kind == 0 || (n.Kind == yaml.DocumentNode && len(n.Content) == 0) {
			continue
		}
		out = append(out, &n)
		if len(out) > MaxDocuments {
			return nil, fmt.Errorf("convert at most %d YAML documents at a time", MaxDocuments)
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("the input contains no YAML document")
	}
	return out, nil
}

var nonName = regexp.MustCompile(`[^a-z0-9]+`)

func slug(s string) string {
	s = strings.Trim(nonName.ReplaceAllString(strings.ToLower(s), "-"), "-")
	if s == "" {
		s = "slo"
	}
	if len(s) > 63 {
		s = strings.Trim(s[:63], "-")
	}
	return s
}

func unique(name string, used map[string]bool) string {
	candidate := name
	for i := 2; used[candidate]; i++ {
		suffix := fmt.Sprintf("-%d", i)
		base := name
		if len(base)+len(suffix) > 63 {
			base = strings.Trim(base[:63-len(suffix)], "-")
		}
		candidate = base + suffix
	}
	used[candidate] = true
	return candidate
}

var labelKey = regexp.MustCompile(`^[a-z][a-z0-9_.-]{0,31}$`)

// labels maps another tool's labels onto Nines labels (at most eight, with
// bounded names and values) and reports what could not be carried over.
func labels(sources ...map[string]string) (map[string]string, []v1.MigrationNote) {
	merged := map[string]string{}
	for _, m := range sources {
		for k, v := range m {
			merged[k] = v
		}
	}
	keys := make([]string, 0, len(merged))
	for k := range merged {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	out := map[string]string{}
	var notes []v1.MigrationNote
	for _, k := range keys {
		v := merged[k]
		nk := strings.ToLower(strings.NewReplacer("/", "_", " ", "_").Replace(k))
		switch {
		case !labelKey.MatchString(nk):
			notes = append(notes, note("lossy", "labels."+k, fmt.Sprintf("Label %q is not a valid Nines label name and was not carried over.", k)))
		case strings.TrimSpace(v) == "" || len(v) > 63:
			notes = append(notes, note("lossy", "labels."+k, fmt.Sprintf("The value of label %q is empty or longer than 63 characters and was not carried over.", k)))
		case len(out) >= 8:
			notes = append(notes, note("lossy", "labels."+k, fmt.Sprintf("Nines keeps at most 8 labels; %q was not carried over.", k)))
		default:
			if nk != k {
				notes = append(notes, note("review", "labels."+k, fmt.Sprintf("Label %q was renamed to %q.", k, nk)))
			}
			out[nk] = v
		}
	}
	return out, notes
}

func percentToTarget(p float64) (float64, error) {
	if math.IsNaN(p) || p <= 0 || p >= 100 {
		return 0, fmt.Errorf("the objective must be a percentage above 0 and below 100, got %v", p)
	}
	return math.Round(p/100*1e12) / 1e12, nil
}

func duration(seconds int64) string {
	switch {
	case seconds%86400 == 0:
		return fmt.Sprintf("%dd", seconds/86400)
	case seconds%3600 == 0:
		return fmt.Sprintf("%dh", seconds/3600)
	default:
		return fmt.Sprintf("%dm", seconds/60)
	}
}

// goDuration formats a policy window the way Nines parses it (no day unit).
func goDuration(seconds int64) string {
	if seconds%3600 == 0 {
		return fmt.Sprintf("%dh", seconds/3600)
	}
	return fmt.Sprintf("%dm", seconds/60)
}

// policies builds the standard multi-window burn-rate policies. Each burn
// rate is the budget fraction consumed over its long window, expressed per
// window length: at 30 days these are the familiar 14.4, 6, 3 and 1.
func policies(window int64, page, ticket bool) ([]map[string]any, []v1.MigrationNote) {
	defs := []struct {
		name, severity string
		short, long    int64
		fraction       float64
		isPage         bool
	}{
		{"page-fast", "critical", 300, 3600, 0.02, true},
		{"page-slow", "critical", 1800, 6 * 3600, 0.05, true},
		{"ticket-fast", "warning", 2 * 3600, dayWindow, 0.10, false},
		{"ticket-slow", "warning", 6 * 3600, 3 * dayWindow, 0.10, false},
	}
	var out []map[string]any
	var notes []v1.MigrationNote
	for _, d := range defs {
		if (d.isPage && !page) || (!d.isPage && !ticket) {
			continue
		}
		if d.long > window {
			notes = append(notes, note("review", "policies."+d.name, fmt.Sprintf("The %s alert looks back %s, longer than this SLO's %s window, so it was left out.", d.name, duration(d.long), duration(window))))
			continue
		}
		burn := math.Round(d.fraction*float64(window)/float64(d.long)*100) / 100
		out = append(out, map[string]any{"name": d.name, "severity": d.severity, "shortWindow": goDuration(d.short), "longWindow": goDuration(d.long), "burnRate": burn, "forSeconds": 0, "minCoverage": 1})
	}
	return out, notes
}
